import pytest

from gruffpy.rule.docs.ignore_directive_reason_rule import IgnoreDirectiveReasonRule
from tests.unit.rule.docs._helpers import default_ctx, make_unit


def test_noqa_without_reason_emits():
    """Report a bare noqa once, recording the directive with no reason.

    Returns:
        None. Asserts that one finding records noqa, an absent reason, and an empty reason string.
    """
    src = "import os  # noqa\n"

    findings = IgnoreDirectiveReasonRule().analyse(make_unit(src), default_ctx())

    assert len(findings) == 1
    assert findings[0].metadata == {"directive": "noqa", "reasonPresent": False, "reason": ""}


def test_noqa_with_substantive_reason_is_skipped():
    """Report nothing for a noqa code followed by a dash and a substantive reason.

    Returns:
        None. Asserts that the rule returns an empty findings list for the supplied noqa.
    """
    src = "from package import name  # noqa: F401 - re-exported public API\n"

    assert IgnoreDirectiveReasonRule().analyse(make_unit(src), default_ctx()) == []


def test_type_ignore_with_generic_reason_still_emits():
    """Report a type: ignore whose only reason is the word ignore, recording that generic reason.

    Returns:
        None. Asserts that one finding records the directive and marks ignore as the supplied reason.
    """
    src = "value = plugin.attr  # type: ignore[attr-defined]  # ignore\n"

    findings = IgnoreDirectiveReasonRule().analyse(make_unit(src), default_ctx())

    assert len(findings) == 1
    assert findings[0].metadata["directive"] == "type: ignore[attr-defined]"
    assert findings[0].metadata["reasonPresent"] is True
    assert findings[0].metadata["reason"] == "ignore"


def test_pragma_no_cover_with_double_dash_reason_is_skipped():
    """Report nothing for a pragma: no cover with a double-dash reason.

    Returns:
        None. Asserts that the rule returns an empty findings list for the supplied pragma.
    """
    src = "if __name__ == '__main__':  # pragma: no cover -- subprocess smoke only\n    pass\n"

    assert IgnoreDirectiveReasonRule().analyse(make_unit(src), default_ctx()) == []


def test_gruff_disable_without_reason_emits():
    """Report a reasonless gruff: disable comment once, naming the full directive.

    Returns:
        None. Asserts that one finding records the complete directive, including the disabled rule ID.
    """
    src = "# gruff: disable=docs.missing-function-docstring\n"

    findings = IgnoreDirectiveReasonRule().analyse(make_unit(src), default_ctx())

    assert len(findings) == 1
    assert findings[0].metadata["directive"] == "gruff: disable=docs.missing-function-docstring"


def test_directive_inside_string_literal_is_skipped():
    """Report nothing for directive text inside a string literal.

    Returns:
        None. Checks that the rule emits no findings for the string literal.
    """
    src = "text = '# noqa'\n"

    assert IgnoreDirectiveReasonRule().analyse(make_unit(src), default_ctx()) == []


def test_generated_file_is_skipped():
    """Skip a file whose header says it is generated.

    Returns:
        None. Asserts that the generated fixture produces no findings even though it contains a bare noqa.
    """
    src = (
        '"""This file is automatically generated from test_typed_mapping.py.\n\n'
        'Do not edit manually, any change will be lost.\n"""  # noqa: E501\n\n'
        "import os  # noqa\n"
    )

    assert IgnoreDirectiveReasonRule().analyse(make_unit(src), default_ctx()) == []


@pytest.mark.parametrize(
    "source",
    [
        "headers = request.headers  # type: ignore[arg-type]  # urllib3#3072\n",
        "from package import name  # noqa: F401 - see mypy#4125\n",
        "value = legacy()  # type: ignore -- GH-1234\n",
    ],
    ids=["second-comment-tracker", "dash-reason-tracker", "tracker-key"],
)
def test_tracker_reference_is_a_substantive_reason(source: str) -> None:
    """Accept an issue reference as the rationale.

    Args:
        source: Suppressed line whose reason is a tracker reference.

    Returns:
        None. Asserts that the supplied line produces no findings.
    """
    assert IgnoreDirectiveReasonRule().analyse(make_unit(source), default_ctx()) == []


def test_noqa_codes_do_not_swallow_a_neighbouring_tool_directive():
    """Report noqa:F401 as reasonless when isort:skip follows it.

    Returns:
        None. Checks that one finding records noqa:F401 alone and marks its reason as absent.
    """
    src = "from _pytest.assertion.util import format_explanation  # noqa:F401, isort:skip\n"

    findings = IgnoreDirectiveReasonRule().analyse(make_unit(src), default_ctx())

    assert len(findings) == 1
    assert findings[0].metadata == {"directive": "noqa:F401", "reasonPresent": False, "reason": ""}

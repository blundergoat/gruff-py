"""Prepare or regenerate the project's `.gruff-py.yaml` for `init`.

A fresh setup starts from registry defaults and the starter ignore list.
Forced regeneration reloads the staged file to check that existing settings survive before replacing it atomically.
The command preserves a legacy YAML or TOML file when it still governs the project.
"""

import os
import tempfile
import tomllib
from contextlib import suppress
from pathlib import Path
from typing import Any

import yaml

from gruffpy.analysis.schema import CONFIG_SCHEMA_VERSION
from gruffpy.config.analysis_config import (
    MINIMUM_SEVERITY_BINARY_DEFAULTS,
    AnalysisConfig,
    DeepScanBudget,
)
from gruffpy.config.exceptions import ConfigError
from gruffpy.config.loader import (
    DEFAULT_YAML_CONFIG_NAME,
    LEGACY_YAML_CONFIG_NAME,
    ConfigLoader,
)
from gruffpy.config.rule_settings import RuleSettings
from gruffpy.rule.registry import RuleRegistry

_HEADER = (
    "# gruff-py configuration - .gruff-py.yaml\n"
    "# Generated by `gruff-py init`. Mirrors RuleRegistry.defaults() plus starter ignores.\n"
    "# Built-in ignores and .gitignore already apply; add project-specific globs below.\n"
    "# After reviewing findings, `gruff-py analyse . --generate-baseline` records known debt.\n"
    "# See docs/configuration.md for the full key reference.\n"
)

DEFAULT_INIT_IGNORED_PATH_PATTERNS = (
    ".agents/",
    ".antigravitycli/",
    ".claude/",
    ".codex/",
    ".github/",
    ".goat-flow/",
    "tests/fixtures/**",
)

_TARGET_CONFIG_NAME = DEFAULT_YAML_CONFIG_NAME
_ACCEPTED_ABBREVIATIONS_COMMENTS = (
    "  # acceptedAbbreviations lets naming rules accept project vocabulary.",
    "  # Configured values replace this seed; they do not merge with it.",
)
_SENSITIVE_EXCLUSIONS_COMMENTS = (
    "# Use sensitiveExclusions to record reviewed exceptions for sensitive-data findings.",
    "# Write each entry by hand with rule, path, and reason; symbol is optional.",
    "# No preview or matched value is ever turned into an entry automatically,",
    "# and every entry reports how many findings it suppressed.",
)


def render_default_config_yaml() -> str:
    """Render the loadable starter config shown to a first-time init user.

    Returns:
        YAML containing registry defaults, starter ignores, and family seed values.
    """
    registry = RuleRegistry.defaults()
    return render_resolved_config_yaml(_default_init_analysis_config(registry))


def render_resolved_config_yaml(config: AnalysisConfig) -> str:
    """Render every supported value from one fully resolved user config.

    Args:
        config: Strictly loaded settings to preserve; empty collections stay empty.

    Returns:
        Canonical YAML whose strict reload must equal ``config``.
    """
    registry = RuleRegistry.defaults()
    scaffold_yaml = yaml.safe_dump(
        _scaffold_document(config),
        sort_keys=False,
        default_flow_style=False,
    )
    allowlists_yaml = _render_allowlists_section(config)
    selection_yaml = yaml.safe_dump(
        _selection_document(config),
        sort_keys=False,
        default_flow_style=False,
    )
    return (
        _HEADER
        + scaffold_yaml
        + allowlists_yaml
        + selection_yaml
        + _render_sensitive_exclusions_section(config)
        + _render_rules_section(config, registry)
    )


def initialise_project_config(project_root: Path, *, force: bool) -> Path:
    """Create or safely regenerate the config requested by the CLI user.

    Args:
        project_root: Project directory where discovery and writing occur.
        force: Whether a valid existing target may be canonically regenerated.

    Returns:
        Path to the freshly written or atomically replaced target.

    Raises:
        ConfigError: An alternate source exists, an existing target requires force or fails strict loading, or safe staging fails.
            Validation or replacement failures also leave any existing config untouched.
    """
    target = project_root / _TARGET_CONFIG_NAME
    discovered_source = existing_config_source(project_root)
    registry = RuleRegistry.defaults()
    registry_defaults = AnalysisConfig.from_registry(registry)

    # A first-time user receives the documented starter values.
    if discovered_source is None:
        resolved_config = _default_init_analysis_config(registry)
    # Legacy YAML and TOML stay authoritative so init cannot change precedence.
    elif discovered_source != target:
        raise ConfigError(_different_source_error(discovered_source, target))
    # An existing target requires explicit acknowledgment before canonical rewrite.
    elif not force:
        raise ConfigError(
            f"{target.name} already exists. Re-run with --force to canonically regenerate it; "
            "all supported settings are preserved, but comments and formatting may change."
        )
    else:
        try:
            resolved_config, _ = ConfigLoader(
                project_root,
                registry_defaults,
                strict=True,
            ).load(target)
        except ConfigError as exc:
            # Example: a user typo such as an unknown top-level key must keep every byte.
            raise ConfigError(f"{target.name} is invalid and was left unchanged: {exc}") from exc

    rendered_yaml = render_resolved_config_yaml(resolved_config)
    _validate_and_atomically_replace(
        target,
        rendered_yaml,
        expected_config=resolved_config,
        registry_defaults=registry_defaults,
    )
    return target


def _default_init_analysis_config(registry: RuleRegistry) -> AnalysisConfig:
    """Build the resolved starter settings used only when no config exists.

    Args:
        registry: Built-in rules whose defaults become generated rule entries.

    Returns:
        Config with starter ignores, per-command binary severity defaults, and deep-scan defaults to write into the generated YAML.
    """
    return (
        AnalysisConfig.from_registry(registry)
        .with_ignored_path_patterns(DEFAULT_INIT_IGNORED_PATH_PATTERNS)
        .with_minimum_severity(MINIMUM_SEVERITY_BINARY_DEFAULTS)
        .with_deep_scan_budget(DeepScanBudget(override="config"))
    )


def _scaffold_document(
    config: AnalysisConfig,
) -> dict[str, Any]:
    """Build the settings users see before allowlists and rule selection.

    Args:
        config: Resolved settings; empty severity mappings and ignored-path collections remain empty.

    Returns:
        YAML-ready settings for canonical regeneration. The deepScanBudget section appears only when the budget comes from config.
    """
    major, minor = config.minimum_python_version
    minimum_severity = {command: severity.value for command, severity in config.minimum_severity.items()}
    document: dict[str, Any] = {
        "schemaVersion": CONFIG_SCHEMA_VERSION,
        "failOn": minimum_severity,
        "minimumPythonVersion": f"{major}.{minor}",
        "outputVolumeHintThreshold": config.output_volume_hint_threshold,
        "paths": {"ignore": list(config.ignored_path_patterns)},
    }
    if config.deep_scan_budget.override == "config":
        document["deepScanBudget"] = {
            "enabled": config.deep_scan_budget.enabled,
            "maxLines": config.deep_scan_budget.max_lines,
            "maxBytes": config.deep_scan_budget.max_bytes,
        }
    return document


def _render_allowlists_section(config: AnalysisConfig) -> str:
    """Render configured abbreviation and dead-code exceptions for the config.

    Args:
        config: Resolved allowlists; empty lists mean no user exceptions are active.

    Returns:
        YAML allowlists section containing abbreviation and dead-code exceptions.
    """
    allowlists = {
        "acceptedAbbreviations": list(config.accepted_abbreviations),
        "deadCode": {
            "symbols": list(config.dead_code_allowlist.symbols),
            "decorators": list(config.dead_code_allowlist.decorators),
            "paths": list(config.dead_code_allowlist.paths),
        },
    }
    nested_yaml = yaml.safe_dump(
        allowlists,
        sort_keys=False,
        default_flow_style=False,
    )
    lines = ["allowlists:", *_ACCEPTED_ABBREVIATIONS_COMMENTS]
    for line in nested_yaml.rstrip("\n").split("\n"):
        lines.append("  " + line)
    return "\n".join(lines) + "\n"


def _render_sensitive_exclusions_section(config: AnalysisConfig) -> str:
    """Show the sensitive-data suppression section, empty by default, with authoring guidance.

    Args:
        config: Resolved settings; an empty list means the project suppresses nothing.

    Returns:
        YAML section listing every configured entry, preceded by the authoring comments.
    """
    entries: list[dict[str, Any]] = []
    # Each entry is regenerated in the user's original order so audit indexes are preserved.
    for exclusion in config.sensitive_exclusions:
        entry: dict[str, Any] = {"rule": exclusion.rule, "path": exclusion.path}
        # With no symbol, the exclusion applies to the matching rule and path regardless of symbol.
        if exclusion.symbol is not None:
            entry["symbol"] = exclusion.symbol
        entry["reason"] = exclusion.reason
        entries.append(entry)
    section_yaml = yaml.safe_dump(
        {"sensitiveExclusions": entries},
        sort_keys=False,
        default_flow_style=False,
    )
    return "\n".join(_SENSITIVE_EXCLUSIONS_COMMENTS) + "\n" + section_yaml


def _selection_document(config: AnalysisConfig) -> dict[str, Any]:
    """Render every resolved rule selector for the regenerated config, including inactive filters.

    Args:
        config: Resolved selection; empty lists keep the corresponding filter inactive.

    Returns:
        YAML-ready include and exclude selectors for the regenerated config.
    """
    return {
        "selection": {
            "tiers": list(config.rule_selection.tiers),
            "pillars": list(config.rule_selection.pillars),
            "rules": list(config.rule_selection.rules),
            "excludePillars": list(config.rule_selection.exclude_pillars),
            "excludeRules": list(config.rule_selection.exclude_rules),
        },
    }


def _different_source_error(source: Path, target: Path) -> str:
    """Explain why init cannot convert or shadow the user's discovered source.

    Args:
        source: Legacy YAML or pyproject path currently authoritative.
        target: Higher-precedence YAML path that init deliberately leaves absent.

    Returns:
        Format-specific recovery guidance for the failed CLI action.
    """
    # YAML users have a non-destructive migration command that writes to a separate output file.
    if source.suffix in {".yaml", ".yml"}:
        return (
            f"Existing gruff config found at {source.name}; {target.name} was not created. "
            "init does not convert config sources. Run `gruff-py migrate-config --output gruff-py.migrated.yaml` "
            "(or `--dry-run` to preview) to migrate the YAML source."
        )
    return (
        f"Existing gruff config found at {source.name}; {target.name} was not created. "
        "init does not convert TOML. Edit [tool.gruff-py] or [tool.gruff] in "
        "pyproject.toml by hand; `migrate-config` supports YAML only."
    )


def _validate_and_atomically_replace(
    target: Path,
    rendered_yaml: str,
    *,
    expected_config: AnalysisConfig,
    registry_defaults: AnalysisConfig,
) -> None:
    """Strictly reload staged YAML, compare semantics, and replace the target.

    Args:
        target: User config path to create or atomically replace.
        rendered_yaml: Canonical full-config YAML awaiting validation.
        expected_config: Resolved settings that must match the settings loaded from the staged YAML.
        registry_defaults: Same rule defaults used to load before and after rendering.

    Returns:
        None; the validated YAML replaces target on success.

    Raises:
        ConfigError: If staging or replacement fails, strict reload rejects the YAML with ConfigError, or the loaded settings differ.
            The target stays unchanged and no partial target is installed.
        ValueError: If strict reload rejects a minimum Python version below the supported minimum.
    """
    staged_path = _write_staged_yaml(target, rendered_yaml)
    try:
        try:
            reloaded_config, _ = ConfigLoader(
                target.parent,
                registry_defaults,
                strict=True,
            ).load(staged_path)
        except ConfigError as exc:
            # If generated YAML contains an unknown key, strict reload reports the validation failure and leaves the target unchanged.
            raise ConfigError(f"Generated {target.name} failed strict validation; target was left unchanged: {exc}") from exc
        # A valid reload can still lose a supported setting, so equality is mandatory.
        if reloaded_config != expected_config:
            raise ConfigError(f"Generated {target.name} failed semantic validation; target was left unchanged.")
        try:
            os.replace(staged_path, target)
        except OSError as exc:
            # If directory permissions prevent the rename, report the failure while the target stays intact.
            raise ConfigError(f"Unable to replace {target.name}; target was left unchanged: {exc}") from exc
    finally:
        # Cleanup must not mask validation or replacement results; suppressed removal errors can leave the stage behind.
        with suppress(OSError):
            staged_path.unlink()


def _umask_derived_file_mode() -> int:
    """Calculate the ordinary creation mode for a new config file from the process umask.

    mkstemp requests mode 0600, subject to the process umask. This helper briefly sets the umask to 0o077 and restores it before returning.

    Returns:
        Permission bits for a new regular file under the active umask.
    """
    active_umask = os.umask(0o077)
    os.umask(active_umask)
    return 0o666 & ~active_umask


def _write_staged_yaml(target: Path, rendered_yaml: str) -> Path:
    """Write and flush canonical YAML to a same-directory temporary path.

    Args:
        target: Final user config whose directory owns the atomic rename boundary.
        rendered_yaml: Complete non-empty YAML text to stage before validation.

    Returns:
        Existing temporary YAML path ready for strict reload.

    Raises:
        ConfigError: When a user filesystem cannot create, write, flush, or
            permission-match the stage; no target bytes are changed.
    """
    try:
        descriptor, raw_staged_path = tempfile.mkstemp(
            prefix=f"{target.name}.",
            suffix=".yaml",
            dir=str(target.parent),
            text=True,
        )
    except OSError as exc:
        # A read-only project directory produces a staging error before any target bytes can change.
        raise ConfigError(f"Unable to stage {target.name}: {exc}") from exc
    staged_path = Path(raw_staged_path)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as staged_file:
            staged_file.write(rendered_yaml)
            staged_file.flush()
            os.fsync(staged_file.fileno())
        # Existing user permissions survive canonical replacement when a target exists.
        if target.exists():
            os.chmod(staged_path, target.stat().st_mode)
        else:
            # A new config uses the ordinary file creation mode allowed by the process umask.
            os.chmod(staged_path, _umask_derived_file_mode())
    except OSError as exc:
        # A write or permission failure leaves the target untouched. Cleanup must preserve the original error.
        with suppress(OSError):
            staged_path.unlink()
        raise ConfigError(f"Unable to stage {target.name}: {exc}") from exc
    return staged_path


def _render_rules_section(config: AnalysisConfig, registry: RuleRegistry) -> str:
    """Show configured rules with catalogue descriptions, using the rule ID when a catalogue entry is absent.

    Args:
        config: Resolved rule settings; an empty map produces an empty rules section.
        registry: Rule catalogue supplying the user-facing descriptions.

    Returns:
        Canonical rules section in YAML with every loaded rule setting.
    """
    # Users see catalogue descriptions before deciding which rule settings to tune.
    descriptions = {rule.definition().id: rule.definition().get_description() for rule in registry.all()}
    lines = ["rules:"]
    # Stable rule order keeps regenerated config diffs easy for users to review.
    for rule_id in sorted(config.rules):
        lines.append(f"  # {descriptions.get(rule_id, rule_id)}")
        entry = _rule_entry(config.rules[rule_id])
        entry_yaml = yaml.safe_dump({rule_id: entry}, sort_keys=False, default_flow_style=False, indent=2)
        for line in entry_yaml.rstrip("\n").split("\n"):
            lines.append("  " + line)
    return "\n".join(lines) + "\n"


def existing_config_source(project_root: Path) -> Path | None:
    """Find the authoritative config that init must leave visible to the user.

    Unreadable or invalid TOML still counts as present so a new YAML file never
    masks the source problem the user needs to fix.

    Args:
        project_root: Directory checked for config files.

    Returns:
        Path to the authoritative config source, or None when init can create a starter config because discovery found no source.
    """
    # YAML takes precedence, matching the config users get during normal scans.
    for name in (DEFAULT_YAML_CONFIG_NAME, LEGACY_YAML_CONFIG_NAME):
        candidate = project_root / name
        if candidate.exists():
            return candidate
    pyproject = project_root / "pyproject.toml"
    # No pyproject means the user has no remaining discoverable config source.
    if not pyproject.exists():
        return None
    try:
        with open(pyproject, "rb") as f:
            data = tomllib.load(f)
    except OSError:
        # Keep unreadable TOML authoritative so init cannot shadow it. The normal config load reports the read error.
        return pyproject
    except tomllib.TOMLDecodeError:
        # Preserve malformed TOML as the source so the next config load can report the parse error.
        return pyproject
    tool = data.get("tool")
    # A pyproject without a tool table contains no gruff settings to preserve.
    if not isinstance(tool, dict):
        return None
    # Either supported Gruff table prevents init from creating a higher-precedence YAML file.
    if "gruff-py" in tool or "gruff" in tool:
        return pyproject
    return None


def _rule_entry(settings: RuleSettings) -> dict[str, Any]:
    """Render a rule's resolved settings for review or editing after init.

    Args:
        settings: Resolved rule values; absent thresholds/options remain omitted.

    Returns:
        YAML-ready mapping with the enabled flag and any resolved thresholds, severity and options.
    """
    entry: dict[str, Any] = {"enabled": settings.enabled}
    # A severity threshold tells users both where the rule fires and how it gates.
    if settings.severity_threshold is not None:
        entry["threshold"] = settings.severity_threshold.threshold
        entry["severity"] = settings.severity_threshold.severity.value
    # Resolved named thresholds can come from registry defaults as well as user config.
    if settings.thresholds:
        entry["thresholds"] = dict(settings.thresholds)
    # Options stay absent when the user has no rule-specific choices to review.
    if settings.options:
        entry["options"] = dict(settings.options)
    return entry

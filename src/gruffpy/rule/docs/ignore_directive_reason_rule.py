"""Check the reasons developers leave beside suppression directives.

A finding points to a directive the reviewer cannot yet assess. A tracker reference can supply that reason.
Files identified by a generated-file header are skipped because the lasting edit belongs in the generator.
The rule keeps `noqa` codes separate from neighbouring directives such as `isort:skip`.
"""

import re
from dataclasses import dataclass

from gruffpy.finding.confidence import Confidence
from gruffpy.finding.finding import Finding
from gruffpy.finding.pillar import Pillar
from gruffpy.finding.rule_tier import RuleTier
from gruffpy.finding.severity import Severity
from gruffpy.parser.analysis_unit import AnalysisUnit
from gruffpy.rule.context import RuleContext
from gruffpy.rule.definition import RuleDefinition
from gruffpy.rule.rule import Rule
from gruffpy.source.comment_scanner import SourceComment, scan_comments

_DIRECTIVE_PATTERNS: tuple[re.Pattern[str], ...] = (
    # Codes stay uppercase even under IGNORECASE, and a comma may lead into another tool's directive.
    re.compile(
        r"(?P<directive>noqa(?:\s*:\s*(?-i:[A-Z]+[0-9]*)(?:[,\s]+(?-i:[A-Z]+[0-9]*))*)?)"
        r"(?=\s*(?:#|--|-|:|,|$))",
        re.IGNORECASE,
    ),
    re.compile(
        r"(?P<directive>type:\s*ignore(?:\[[^\]]+\])?)(?=\s*(?:#|--|-|:|$))",
        re.IGNORECASE,
    ),
    re.compile(
        r"(?P<directive>pyright:\s*ignore(?:\[[^\]]+\])?)(?=\s*(?:#|--|-|:|$))",
        re.IGNORECASE,
    ),
    re.compile(r"(?P<directive>pragma:\s*no\s+cover)(?=\s*(?:#|--|-|:|$))", re.IGNORECASE),
    re.compile(
        r"(?P<directive>gruff:\s*disable(?:-next|-file)?\s*=\s*[A-Za-z0-9_.-]+"
        r"(?:\s*,\s*[A-Za-z0-9_.-]+)*)(?=\s*(?:#|--|-|:|$))",
        re.IGNORECASE,
    ),
)
_GENERIC_REASONS = frozenset(
    {
        "because",
        "fix",
        "ignore",
        "needed",
        "silence",
        "temporary",
        "todo",
        "works",
    }
)
_WORD_PATTERN = re.compile(r"[A-Za-z][A-Za-z0-9_-]*")
# ``urllib3#3072``, ``GH-1234`` and ``#1234`` each name the issue that explains the suppression.
_TRACKER_REFERENCE = re.compile(r"\b[A-Za-z][\w.-]*#\d+\b|\b[A-Z]{2,}-\d+\b|(?<![\w#])#\d{2,}\b")
# A second comment starts at a ``#`` that opens the tail or follows whitespace, not one inside ``urllib3#3072``.
_SECOND_COMMENT = re.compile(r"(?:^|\s)#")
# Another tool's directive after a comma, such as ``isort:skip``, is not a rationale.
_FOREIGN_DIRECTIVE = re.compile(r"[A-Za-z][\w.-]*\s*:\s*[\w.,=\[\]-]+")
# Generated-file headers mean lasting edits belong in the generator rather than the emitted file.
# Anchor "generated by" to header openings or "this file/code/module is/was generated by" so handwritten prose still scans.
_GENERATED_MARKER = re.compile(
    r"automatically generated|auto-generated|do not edit|"
    r"(?:^\s*(?:#\s*|['\"]{3}\s*)?(?:(?:this\s+)?(?:file|code|module)\s+(?:(?:is|was)\s+)?)?"
    r"|\bthis\s+(?:file|code|module)\s+(?:is|was)\s+)generated by\b",
    re.IGNORECASE | re.MULTILINE,
)
_GENERATED_HEADER_LINES = 10


@dataclass(frozen=True, slots=True)
class _DirectiveMatch:
    """Record a suppression comment and the reason text found beside it.

    The rule uses this record to decide whether the comment needs a finding.
    The location points a reviewer back to the directive they can amend.
    """

    comment: SourceComment
    directive: str
    reason: str
    has_reason: bool


class IgnoreDirectiveReasonRule(Rule):
    """Report suppression comments that lack a substantive reason.

    A code reviewer can use the finding to ask why a warning was suppressed at this location.
    The rule reads actual comment tokens so directive examples inside strings stay quiet.
    """

    ID = "docs.ignore-directive-reason"

    def definition(self) -> RuleDefinition:
        """Return the rule metadata used by the registry and reporters.

        Returns:
            Definition for the ignore directive rationale rule.
        """
        return RuleDefinition(
            id=self.ID,
            name="Ignore directive reason",
            pillar=Pillar.DOCUMENTATION,
            tier=RuleTier.V01,
            default_severity=Severity.WARNING,
            confidence=Confidence.HIGH,
        )

    def analyse(self, unit: AnalysisUnit, context: RuleContext) -> list[Finding]:
        """Analyze source comments for unexplained suppression directives.

        Args:
            unit: Source unit whose comments should be scanned.
            context: Rule execution context. Unused; present for the rule API.

        Returns:
            Findings for suppression comments without substantive reasons. A generated-file marker in the first ten lines skips the scan
            and returns an empty list.
        """
        del context
        # A generated file is rewritten by its generator, so a reason written into it would not survive.
        if _GENERATED_MARKER.search("\n".join(unit.source.splitlines()[:_GENERATED_HEADER_LINES])):
            return []
        definition = self.definition()
        return [
            _directive_finding(unit, definition, match)
            for comment in scan_comments(unit.source)
            if (match := _unexplained_directive(comment)) is not None
        ]


def _unexplained_directive(comment: SourceComment) -> _DirectiveMatch | None:
    """Return the first suppression directive in a comment when the text beside it lacks a substantive rationale.

    Patterns run in `_DIRECTIVE_PATTERNS` order so a substantive reason on the first matched directive ends the check cleanly.

    Args:
        comment: Scanned Python comment token whose body text is checked for suppression directives.

    Returns:
        `_DirectiveMatch` carrying the comment, directive, and extracted reason when unexplained; None when no directive matches or the reason is
        substantive.
    """
    body = comment.body
    # Check each supported linter, type-checker, coverage, and gruff suppression pattern in priority order.
    for pattern in _DIRECTIVE_PATTERNS:
        match = pattern.search(body)
        # Move on to the next directive family when this pattern does not appear in the comment.
        if match is None:
            continue
        directive = match.group("directive").strip()
        reason = _extract_reason(body, match.end()).strip()
        # A substantive explanation or issue tracker reference satisfies reviewers, so suppress the finding.
        if _is_substantive_reason(reason):
            return None
        return _DirectiveMatch(
            comment=comment,
            directive=directive,
            reason=reason,
            has_reason=bool(reason),
        )
    return None


def _extract_reason(body: str, directive_end: int) -> str:
    """Extract the developer's rationale after a matched directive, stripping leading separators or foreign directives.

    Handles second inline comments (`# ...`) and common separators (`,`, `--`, `-`, `:`), while refusing to treat a neighbouring tool directive
    such as `, isort:skip` as an explanation.

    Args:
        body: Full comment body containing the matched suppression directive.
        directive_end: Character offset immediately after the matched directive token.

    Returns:
        Stripped rationale text; an empty string when nothing follows or only another tool directive follows after a comma.
    """
    tail = body[directive_end:].strip()
    # Nothing after the directive means the developer left a bare suppression with no rationale.
    if not tail:
        return ""
    second_comment = _SECOND_COMMENT.search(tail)
    # A trailing `# ...` (for example `# type: ignore[arg-type]  # urllib3#3072`) carries the rationale after `#`.
    if second_comment is not None:
        return tail[second_comment.end() :].strip()
    # A comma may introduce another tool directive (`# noqa:F401, isort:skip`), which must not count as a reason.
    if tail.startswith(","):
        remainder = tail[1:].strip()
        return "" if _FOREIGN_DIRECTIVE.fullmatch(remainder) else remainder
    # Strip `--`, `-`, or `:` separators developers commonly place between a directive and its explanation.
    if tail.startswith("--"):
        return tail[2:].strip()
    if tail.startswith("-"):
        return tail[1:].strip()
    if tail.startswith(":"):
        return tail[1:].strip()
    return tail


def _is_substantive_reason(reason: str) -> bool:
    """Accept a suppression rationale that cites an issue tracker reference or at least two non-generic words.

    Prevents single-word filler like `# noqa -- temporary` or `# type: ignore  # fix` from silencing reviewer visibility.

    Args:
        reason: Stripped rationale text extracted after the directive; empty string when omitted.

    Returns:
        True when the text includes a tracker key (such as `GH-1234`) or two meaningful words; False for empty or filler text.
    """
    # A tracker reference (for example `urllib3#3072` or `GH-1234`) points reviewers to the full context elsewhere.
    if _TRACKER_REFERENCE.search(reason):
        return True
    words = [word.lower() for word in _WORD_PATTERN.findall(reason)]
    # Empty or punctuation-only text gives the reviewer no explanation.
    if not words:
        return False
    # Reject lone generic filler words like `ignore`, `temporary`, or `todo`.
    if len(words) == 1 and words[0] in _GENERIC_REASONS:
        return False
    meaningful = [word for word in words if word not in _GENERIC_REASONS]
    return len(meaningful) >= 2


def _directive_finding(
    unit: AnalysisUnit,
    definition: RuleDefinition,
    match: _DirectiveMatch,
) -> Finding:
    """Build the finding reported on the comment line of a directive that lacks a substantive reason.

    The message says the directive is used without a reason when the extracted reason is empty and with a generic reason otherwise; the remediation
    text is fixed.

    Args:
        unit: Analysis unit whose display path names the finding's file.
        definition: Rule definition that supplies the rule id, default severity, pillar, tier, confidence and secondary pillars.
        match: Unexplained directive whose comment line, directive text and reason fill the finding.

    Returns:
        A Finding that starts and ends on the directive comment's line, with the directive, reasonPresent and reason recorded in its metadata.
    """
    reason_message = "without a reason" if not match.has_reason else "with a generic reason"
    return Finding(
        rule_id=definition.id,
        message=f"Suppression directive {match.directive!r} is used {reason_message}.",
        file_path=unit.file.display_path,
        line=match.comment.line,
        severity=definition.default_severity,
        pillar=definition.pillar,
        tier=definition.tier,
        confidence=definition.confidence,
        end_line=match.comment.line,
        remediation=("Add a short rationale that names the compatibility, framework, or testing reason for the suppression."),
        secondary_pillars=definition.secondary_pillars,
        metadata={
            "directive": match.directive,
            "reasonPresent": match.has_reason,
            "reason": match.reason,
        },
    )
